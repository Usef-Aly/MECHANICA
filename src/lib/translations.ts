export function localizeTopic(topic: any, lang: 'en' | 'ar'): any {
  if (lang === 'en') return topic;
  const translation = PRESET_TOPIC_TRANSLATIONS[topic.id]?.ar;
  if (!translation) return topic;

  return {
    ...topic,
    title: translation.title,
    category: translation.category,
    summary: translation.summary,
    nodes: topic.nodes.map((node: any) => {
      const nodeTrans = translation.nodes[node.id];
      if (nodeTrans) {
        return {
          ...node,
          label: nodeTrans.label,
          description: nodeTrans.description,
          statusLabel: nodeTrans.statusLabel || node.statusLabel
        };
      }
      return node;
    }),
    simulation: {
      ...topic.simulation,
      params: topic.simulation.params.map((p: any) => {
        const pTrans = translation.params[p.id];
        if (pTrans) {
          return {
            ...p,
            label: pTrans.label,
            description: pTrans.description
          };
        }
        return p;
      })
    },
    steps: topic.steps.map((step: any, idx: number) => {
      const stepTrans = translation.steps[idx];
      if (stepTrans) {
        return {
          ...step,
          title: stepTrans.title,
          description: stepTrans.description
        };
      }
      return step;
    }),
    realWorldApplications: translation.realWorldApplications || topic.realWorldApplications,
    qAndA: translation.qAndA || topic.qAndA
  };
}

